import fs from 'node:fs';
const layout=fs.readFileSync('public/work/call-layout.js','utf8');
let html=fs.readFileSync('public/work/call.html','utf8').replace(/\/\* BEGIN CALL LAYOUT \*\/[\s\S]*?\/\* END CALL LAYOUT \*\/\n?/, '');
html=html.replace('<script>', '<script>/* BEGIN CALL LAYOUT */\n'+layout+'/* END CALL LAYOUT */\n');
fs.writeFileSync('public/work/call.html',html);
fs.writeFileSync('mobile/src/lib/call-document.ts',`// Generated by scripts/sync-call-document.mjs; edit public/work/call.html.\nexport const CALL_DOCUMENT = ${JSON.stringify(html)};\n`);
