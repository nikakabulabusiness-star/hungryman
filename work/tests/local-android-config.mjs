import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';
const require = createRequire(import.meta.url);
const {testConfig} = require('../mobile/scripts/build-local-android.cjs');
const original = JSON.parse(fs.readFileSync('mobile/app.json','utf8'));
const before = JSON.stringify(original);
const local = testConfig(original);
assert.equal(JSON.stringify(original), before, 'production config must not change');
assert.notEqual(local.expo.android.package, original.expo.android.package);
assert.equal(local.expo.android.package, 'ge.hungryman.work.local');
assert.equal(local.expo.updates.enabled, false);
assert.equal(local.expo.updates.url, undefined);
assert.equal(local.expo.extra.eas, undefined, 'unconfigured test package must not register production Expo push tokens');
assert.notDeepEqual(local.expo.runtimeVersion, original.expo.runtimeVersion);
assert.deepEqual(local.expo.ios, original.expo.ios);
assert.deepEqual(local.expo.plugins, original.expo.plugins);
const missing = spawnSync(process.execPath,['mobile/scripts/build-local-android.cjs','--check'], {env:{...process.env,ANDROID_HOME:'',ANDROID_SDK_ROOT:''},encoding:'utf8'});
assert.equal(missing.status,1);
assert.match(missing.stderr,/ANDROID_HOME/);
assert.ok(!fs.existsSync('mobile/outputs'), 'failed prerequisites must not produce an APK');
console.log('PASS: isolated Android package, embedded bundle, production config preserved, missing SDK fails before writes.');
